/**
 * Generates verified fallback puzzles for all standard `deep_cave` presets
 * (`easy`, `normal`, `hard`, `expert`) and writes `src/levels/deep_cave/seedBank.js`.
 *
 * Usage: node scripts/generate_seed_bank.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEEP_CAVE_GENERATOR_VERSION } from '../src/constants.js';
import { DEEP_CAVE_PRESETS } from '../src/levels/deep_cave/presets.js';
import { generateDeepCavePuzzle } from '../src/levels/deep_cave/generator.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_PATH = path.resolve(__dirname, '../src/levels/deep_cave/seedBank.js');

const PRESET_IDS = ['easy', 'normal', 'hard', 'expert'];
const SEEDS_PER_PRESET = 2;

const bank = {};

for (const presetId of PRESET_IDS) {
  const settings = DEEP_CAVE_PRESETS[presetId];
  bank[presetId] = [];
  let candidateIdx = 0;

  while (bank[presetId].length < SEEDS_PER_PRESET && candidateIdx < 50) {
    const seed = `seedbank_${presetId}_${candidateIdx++}`;
    const t0 = performance.now();
    const puzzle = generateDeepCavePuzzle(null, settings, null, seed);
    const dt = performance.now() - t0;

    if (!puzzle?.diagnostics?.firstPassMissionSolved) continue;
    if (puzzle.steps < settings.targetSteps || puzzle.steps > settings.targetSteps + 1) continue;

    // Strip internal diagnostics before embedding in static bundle
    const { diagnostics: _diag, ...cleanPuzzle } = puzzle;
    bank[presetId].push(cleanPuzzle);
    console.log(
      `[seed-bank] ${presetId} #${bank[presetId].length}: seed=${seed} steps=${puzzle.steps} (${dt.toFixed(1)}ms)`
    );
  }

  if (bank[presetId].length < SEEDS_PER_PRESET) {
    throw new Error(`Failed to populate seed bank for preset "${presetId}"`);
  }
}

const fileContent = `/**
 * Static CI-verified fallback puzzles for \`deep_cave\` standard presets.
 * Auto-generated by \`scripts/generate_seed_bank.mjs\` (generator v${DEEP_CAVE_GENERATOR_VERSION}).
 */

import { detectDeepCavePresetId } from './presets.js';

export const DEEP_CAVE_SEED_BANK_VERSION = ${DEEP_CAVE_GENERATOR_VERSION};

export const DEEP_CAVE_SEED_BANK = ${JSON.stringify(bank)};

/**
 * Returns a fresh clone of a verified fallback puzzle for standard presets
 * (\`easy\`, \`normal\`, \`hard\`, \`expert\`), or \`null\` for \`custom\` settings.
 */
export function getFallbackDeepCavePuzzle(settings, seedHint = null) {
  const presetId = typeof settings === 'string'
    ? settings
    : detectDeepCavePresetId(settings);
  const entries = DEEP_CAVE_SEED_BANK[presetId];
  if (!Array.isArray(entries) || entries.length === 0) return null;

  let idx = 0;
  if (seedHint != null) {
    const str = String(seedHint);
    let h = 0;
    for (let i = 0; i < str.length; i++) {
      h = (h * 31 + str.charCodeAt(i)) >>> 0;
    }
    idx = h % entries.length;
  }

  const chosen = entries[idx];
  return JSON.parse(JSON.stringify(chosen));
}
`;

fs.writeFileSync(OUT_PATH, fileContent, 'utf8');
const stats = fs.statSync(OUT_PATH);
console.log(`Wrote ${OUT_PATH} (${(stats.size / 1024).toFixed(1)} KB)`);
